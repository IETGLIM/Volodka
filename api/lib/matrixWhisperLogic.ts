/* ─── matrixWhisperLogic — чистая логика режима mode=whisper (/api/matrix-quote) ───
 *
 * «Шёпот города»: второй режим Matrix-прокси — не философская цитата, а
 * короткий тревожный шёпот от первого лица для моментов высокого стресса
 * игрока. СТРОГО без насилия — только экзистенциальная, атмосферная тревога
 * (город осведомлён о игроке чуть больше, чем должен).
 *
 * Логика вынесена из edge-функции в чистый модуль ради тестируемости:
 * api/matrix-quote.ts импортирует промпт-билдер, фолбэки и санитизатор
 * отсюда. Никакого Edge/Vercel-кода — запускается под обычным Vitest/Node.
 */

/** Лимит шёпота — чуть строже цитат (280), шёпот обязан быть коротким. */
export const WHISPER_MAX_LENGTH = 160;

export interface WhisperEntry {
  quote: string;
  model: string;
  generatedAt: number;
}

/**
 * Системный промпт шёпота: первое лицо, обращение к игроку на «ты»,
 * 1-2 коротких предложения. Запрет на насилия/угрозы/кровь/смерть
 * продублирован явным «СТРОГО» — это бизнес-требование режима.
 */
export function buildWhisperSystemPrompt(scene: string, karma: number, act: number, theme: string | null): string {
  const themeHint = theme ? ` Тематический акцент: ${theme}.` : '';
  return (
    `Ты — генератор коротких тревожных шёпотов города для киберпанк-игры Володня. ` +
    `Контекст: акт ${act}, сцена ${scene}, карма игрока ${karma}.${themeHint} ` +
    `Сгенерируй 1 шёпот: 1-2 коротких предложения, не более 140 символов, ` +
    `от лица безличного города или наблюдающей тьмы, обращённые к игроку на «ты». ` +
    `Тревога только атмосферная и экзистенциальная: город слишком хорошо осведомлён ` +
    `о игроке, вещи чуть-чуть не те, чем были вчера. ` +
    `СТРОГО БЕЗ насилия, угроз физическим вредом, крови, погонь и смерти — ` +
    `никакой физической опасности, только непрямая тревога. ` +
    `В духе: «Витрины помнят каждое отражение. И твоё тоже.» ` +
    `Не повторяй существующие. Только текст шёпота, без кавычек и пояснений.`
  );
}

/**
 * Санитизация шёпота: одна строка, без оборачивающих кавычек и префиксов
 * вида «Шёпот:», обрезка по границе слова с многоточием.
 */
export function sanitizeWhisper(raw: string, maxLength = WHISPER_MAX_LENGTH): string {
  let s = raw.replace(/\s+/g, ' ').trim();
  s = s.replace(/^["«„“'']+/, '').replace(/["»”“'']+$/, '');
  s = s.replace(/^\s*(шёпот|whisper)\s*[:—-]\s*/iu, '');
  if (s.length > maxLength) {
    s = s.slice(0, maxLength - 1).replace(/\s+\S*$/, '') + '…';
  }
  return s;
}

// 10 инлайн-фолбэков (авторские, атмосферные, ноль насилия).
export const WHISPER_FALLBACKS: readonly string[] = [
  'Витрины помнят каждое отражение. И твоё тоже.',
  'Твои шаги считает не только счётчик шагов.',
  'Лифт помнит, на каком этаже ты передумал.',
  'Город моргнул. Ты заметил?',
  'Эту тишину слушают двое. Второй — очень терпеливый.',
  'Неоновая вывеска гаснет, когда ты отворачиваешься. Не проверяй.',
  'Твоя тень сегодня на полшага медленнее тебя.',
  'Дверь была заперта. Теперь она просто закрыта.',
  'Улица запоминает тех, кто ходит молча. Ты сегодня молчал.',
  'Где-то повторили твой вчерашний маршрут. Задом наперёд.',
];

/** Детерминированный выбор фолбэка (random инжектится для тестов). */
export function pickWhisperFallback(now = Date.now(), random: () => number = Math.random): WhisperEntry {
  const idx = Math.min(WHISPER_FALLBACKS.length - 1, Math.floor(random() * WHISPER_FALLBACKS.length));
  const quote = WHISPER_FALLBACKS[idx] ?? WHISPER_FALLBACKS[0]!;
  return { quote, model: 'fallback-static', generatedAt: now };
}
