/* ─── Idle Monologues — Volodka's mutterings when standing still ───
 *
 * Fires when the player has been idle (no movement input) for ~25-35 seconds
 * in a scene. Adds Disco-Elysium-style introspective depth to exploration.
 *
 * Rate-limited: max 1 idle thought per 60s, never during cutscenes/combat/
 * dialogue. Thoughts are recorded in the persistent journal (thoughtHistory)
 * via the same volodka:thought → addThought pipeline as scene entry thoughts.
 *
 * Resolution: pick a random line from the appropriate karma/stress band.
 * Stress ≥ 70 takes priority over karma branches.
 */

import type { SceneId } from '@/shared/types/game';
import type { ThoughtContext, ThoughtText } from './sceneEntryThoughts';

/** Minimum idle time (seconds) before an idle monologue can fire. */
export const IDLE_MONOLOGUE_MIN_DELAY_S = 25;
/** Maximum idle time (seconds) before an idle monologue fires (random within range). */
export const IDLE_MONOLOGUE_MAX_DELAY_S = 35;
/** Cooldown (seconds) between idle monologues. */
export const IDLE_MONOLOGUE_COOLDOWN_S = 60;

const HIGH_KARMA = 65;
const LOW_KARMA = 30;
const HIGH_STRESS = 70;

export interface IdleMonologueBand {
  /** Shown when stress ≥ 70 (overrides karma). */
  highStress?: readonly string[];
  /** Shown when karma ≥ 65. */
  high?: readonly string[];
  /** Shown when karma ≤ 30. */
  low?: readonly string[];
  /** Default band — neutral karma, normal stress. */
  neutral: readonly string[];
}

export type IdleMonologueConfig = IdleMonologueBand | ThoughtText;

function resolveBand(
  config: IdleMonologueConfig,
  ctx: ThoughtContext,
): readonly string[] {
  if (typeof config === 'function') {
    return [config(ctx)];
  }
  if (typeof config === 'string') {
    return [config];
  }
  if (ctx.stress >= HIGH_STRESS && config.highStress && config.highStress.length > 0) {
    return config.highStress;
  }
  if (ctx.karma >= HIGH_KARMA && config.high && config.high.length > 0) {
    return config.high;
  }
  if (ctx.karma <= LOW_KARMA && config.low && config.low.length > 0) {
    return config.low;
  }
  return config.neutral;
}

/** Deterministic-ish pick using a seed (avoids per-frame Math.random in hot path). */
function pickLine(lines: readonly string[], seed: number): string {
  if (lines.length === 0) return '';
  if (lines.length === 1) return lines[0];
  const idx = Math.abs(seed) % lines.length;
  return lines[idx] ?? lines[0];
}

export interface IdleMonologueResolverOptions {
  /** A seed for deterministic picking (e.g., Date.now() truncated). */
  seed: number;
}

/** Resolve which idle monologue (if any) to show. Returns null if scene has none. */
export function resolveIdleMonologue(
  sceneId: SceneId,
  ctx: ThoughtContext,
  options: IdleMonologueResolverOptions,
): string | null {
  const config = IDLE_MONOLOGUES[sceneId];
  if (!config) return null;
  const lines = resolveBand(config, ctx);
  if (lines.length === 0) return null;
  return pickLine(lines, options.seed);
}

/**
 * Pick a single idle monologue line for the given scene + player state.
 * Uses the provided RNG (defaults to Math.random) for line selection.
 * Returns null if the scene has no idle monologue pool.
 *
 * This is the primary entry point used by the idle monologue system
 * (src/engine/player/idleMonologueSystem.ts).
 */
export function pickIdleMonologue(
  sceneId: SceneId,
  karma: number,
  stress: number,
  rng: () => number = Math.random,
): string | null {
  const config = IDLE_MONOLOGUES[sceneId];
  if (!config) return null;
  const ctx: ThoughtContext = {
    karma,
    stress,
    energy: 50,
    currentAct: 1,
    flags: {},
  };
  const lines = resolveBand(config, ctx);
  if (lines.length === 0) return null;
  if (lines.length === 1) return lines[0];
  const idx = Math.floor(rng() * lines.length);
  return lines[idx] ?? lines[0];
}

