/* ─── Volodka RPG – Score Events (v4.55.0 «Стихосложение») ───
 * Очки за один прохождение: боевые победы, собранные стихи, квесты,
 * достижения и открытие сцен. Полностью additive-домен: только событие
 * для HUD/меню — сама арифметика живёт в engine/score/scoreEngine.ts.
 */

export interface ScoreEvents {
  /** Общий счёт забега изменился (после каждой мутации, включая сброс). */
  'score:changed': {
    /** Новый суммарный счёт забега. */
    score: number;
    /** Дельта последнего начисления (0 при сбросе). */
    delta: number;
    /** Машиный ключ причины ('reset' при обнулении). */
    reason: string;
    /** Человекочитаемая подпись для HUD, например «Враг повержен». */
    label?: string;
  };
}
